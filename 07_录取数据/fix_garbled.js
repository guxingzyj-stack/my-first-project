// ==================== 执行修复 ====================
console.log('='.repeat(50));
console.log('🔧 修复数据库乱码');
console.log('='.repeat(50));

// 先备份
const fs = require('fs');
const backupPath = DB_PATH + '.bak';
if (!fs.existsSync(backupPath)) {
  fs.copyFileSync(DB_PATH, backupPath);
  console.log('📦 已备份数据库到', backupPath);
}

let fixedCount = 0;
let failedCount = 0;

// 获取所有含乱码的记录
const badRows = db.prepare(
  "SELECT rowid as rid, province, subject, batch FROM major_scores WHERE province LIKE ? OR subject LIKE ? OR batch LIKE ?"
).all(`%${R}%`, `%${R}%`, `%${R}%`);

console.log(`\n找到 ${badRows.length} 条乱码记录\n`);

const updateStmt = db.prepare(
  "UPDATE major_scores SET province=?, subject=?, batch=? WHERE rowid=?"
// Note: using rid alias
);

const deleteStmt = db.prepare("DELETE FROM major_scores WHERE rowid=?");

const fixAll = db.transaction(() => {
  for (const row of badRows) {
    let newProv = row.province;
    let newSubj = row.subject;
    let newBatch = row.batch;
    let canFix = true;

    // 修复省份
    if (newProv.includes(R)) {
      if (PROVINCE_MAP[newProv]) {
        newProv = PROVINCE_MAP[newProv];
      } else {
        console.warn('  ❌ 无法修复省份:', JSON.stringify(row.province), 'rowid:', row.rid);
        canFix = false;
      }
    }

    // 修复科类
    if (newSubj.includes(R)) {
      if (SUBJECT_MAP[newSubj]) {
        newSubj = SUBJECT_MAP[newSubj];
      } else {
        console.warn('  ❌ 无法修复科类:', JSON.stringify(row.subject), 'rowid:', row.rid);
        canFix = false;
      }
    }

    // 修复批次
    if (newBatch.includes(R)) {
      const fixed = fixBatch(newBatch);
      if (fixed) {
        newBatch = fixed;
      } else {
        console.warn('  ❌ 无法修复批次:', JSON.stringify(row.batch), 'rowid:', row.rid);
        canFix = false;
      }
    }

    if (canFix) {
      try {
        updateStmt.run(newProv, newSubj, newBatch, row.rid);
        fixedCount++;
      } catch (e) {
        // UNIQUE constraint 冲突 = 修复后和已有正常记录重复，直接删除乱码记录
        if (e.message.includes('UNIQUE')) {
          deleteStmt.run(row.rid);
          fixedCount++;
        } else {
          console.warn('  ❌ 更新失败:', e.message, 'rowid:', row.rid);
          failedCount++;
        }
      }
    } else {
      // 无法修复的也删除，避免污染下拉框
      deleteStmt.run(row.rid);
      failedCount++;
    }
  }
});

fixAll();

// 验证
const remaining = db.prepare(
  "SELECT COUNT(*) as cnt FROM major_scores WHERE province LIKE ? OR subject LIKE ? OR batch LIKE ?"
).get(`%${R}%`, `%${R}%`, `%${R}%`);

const total = db.prepare('SELECT COUNT(*) as cnt FROM major_scores').get();

console.log('\n' + '='.repeat(50));
console.log(`✅ 修复完成：${fixedCount} 条修复/删除，${failedCount} 条无法修复已删除`);
console.log(`📊 剩余乱码: ${remaining.cnt} 条`);
console.log(`📊 总记录数: ${total.cnt}`);
console.log('='.repeat(50));

db.close();
